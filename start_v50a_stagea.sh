RUNID="${RUNID:-pgg2_v50a_stagea_$(date +%Y%m%d_%H%M%S)}"
mkdir -p logs data
echo "$RUNID" > current_pgg2_v50a_stagea_runid.txt

export PGG2_V48_OUT_MD="/root/piggy/V50A_STAGEA_V48_DECISIONS.md"
export PGG2_V48_OUT_JSONL="/root/piggy/data/v50a_stagea_decisions.jsonl"

PYTHON_BIN="${PYTHON_BIN:-/root/piggy/venv/bin/python}"
if [[ ! -x "$PYTHON_BIN" ]]; then
  PYTHON_BIN="$(command -v python3)"
fi

exec "$PYTHON_BIN" -u pgg2_v50a_stagea_live.py 2>&1 | tee -a "logs/${RUNID}.log"
