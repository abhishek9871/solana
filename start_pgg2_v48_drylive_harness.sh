# Explicitly keep rejected production paths off.
export PGG2_ENTRY_SNAPSHOT_BANK_ENABLED=0
export PGG2_ENTRY_SNAPSHOT_BANK_LIVE_ELIGIBLE=0
export PGG2_SAME_ROUTE_RECOVERY_ACTUAL_ENTRY_ENABLED=0
export PGG2_PROTECTED_HOLD_ENABLED=0
export PGG2_JITO_ENABLED=0
export PGG2_LIVE_SEND_MODE=rpc

if [[ "${PGG2_V48_LIVE_SMOKE_ENABLED:-0}" == "1" ]]; then
  RUNID="${RUNID:-pgg2_v48_live_smoke_$(date +%Y%m%d_%H%M%S)}"
else
  RUNID="${RUNID:-pgg2_v48_drylive_harness_$(date +%Y%m%d_%H%M%S)}"
fi
mkdir -p logs data
echo "$RUNID" > current_pgg2_v48_drylive_runid.txt
if [[ "${PGG2_V48_LIVE_SMOKE_ENABLED:-0}" == "1" ]]; then
  echo "$RUNID" > current_pgg2_v48_live_smoke_runid.txt
fi

PYTHON_BIN="${PYTHON_BIN:-/root/piggy/venv/bin/python}"
if [[ ! -x "$PYTHON_BIN" ]]; then
  PYTHON_BIN="$(command -v python3)"
fi

exec "$PYTHON_BIN" -u pgg2_v48_drylive_harness.py \
  --out-md "${PGG2_V48_OUT_MD:-V48_CORRECTED_DRYLIVE_RESULT.md}" \
  --out-jsonl "${PGG2_V48_OUT_JSONL:-data/v48_drylive_decisions.jsonl}" \
  --debug-log "logs/${RUNID}.debug.log" \
  --max-seconds "${PGG2_V48_MAX_SECONDS:-2100}" \
  --target-non-neg-closes "${PGG2_V48_TARGET_CLOSED_NONNEG:-10}" \
  --max-open-positions "${PGG2_V48_MAX_OPEN:-2}" \
  --backfill-ttl-ms "${PGG2_V48_BACKFILL_TTL_MS:-1000}" \
  --clean-close-entry-floor-sol "${PGG2_V48_CLEAN_CLOSE_ENTRY_FLOOR_SOL:-0.00120}" \
  --profit-reentry-block-ms "${PGG2_V48_PROFIT_REENTRY_BLOCK_MS:-30000}" \
  --concentration-guard-max-buyers "${PGG2_V48_CONCENTRATION_GUARD_MAX_BUYERS:-4}" \
  --concentration-guard-top-share "${PGG2_V48_CONCENTRATION_GUARD_TOP_SHARE:-0.55}" \
  --velocity-edge-max-buyers "${PGG2_V48_VELOCITY_EDGE_MAX_BUYERS:-4}" \
  --velocity-edge-min-buy-sol "${PGG2_V48_VELOCITY_EDGE_MIN_BUY_SOL:-6.0}" \
  --velocity-edge-floor-sol "${PGG2_V48_VELOCITY_EDGE_FLOOR_SOL:-0.00140}" \
  --recent-v47i-veto-memory-ms "${PGG2_V48_RECENT_V47I_VETO_MEMORY_MS:-2000}" \
  --post-stop-drain-seconds "${PGG2_V48_POST_STOP_DRAIN_SECONDS:-300}" \
  --failed-buy-fee-budget-sol "${PGG2_V48_FAILED_BUY_FEE_BUDGET_SOL:-0.00300}" \
  --progress-interval-seconds "${PGG2_V48_PROGRESS_INTERVAL_SECONDS:-60}"
